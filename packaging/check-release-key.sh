#!/bin/sh
# Проверяет, что packaging/minisign.pub — настоящий ключ выпусков, а не
# ключ разработчика. Печатает идентификатор ключа; с ключом разработчика
# завершается с ошибкой.
#
# ======================================================================
#  ВНИМАНИЕ! Ключ в packaging/minisign.pub встраивается в программу:
#  sshdeck ставит обновление, только если его подпись сделана этим
#  ключом. Пока в репозитории лежит ВРЕМЕННЫЙ КЛЮЧ РАЗРАБОТЧИКА (он
#  создан для тестов, его секретная половина нигде не хранится
#  надёжно), выпускать с ним ничего нельзя:
#
#    - собранные с ним программы будут доверять чужому ключу;
#    - подписать им выпуск нечем, а подпись другим ключом программы с
#      этим ключом отвергнут.
#
#  Перед первым выпуском с обновлениями создайте свой ключ (см.
#  packaging/README.md, раздел «Signing key»), закоммитьте новый
#  packaging/minisign.pub и только потом собирайте пакеты.
#
#  Идентификаторы ключей разработчика перечислены в DEV_KEY_IDS ниже —
#  скрипты сборки и подписи отказываются работать с ними. Не удаляйте
#  их из списка.
# ======================================================================
set -eu
cd "$(dirname "$0")/.."

# Ключи разработчика (идентификатор minisign, 16 шестнадцатеричных цифр).
DEV_KEY_IDS="AE5012490955CDF5"

pub=packaging/minisign.pub
[ -f "$pub" ] || { echo "Нет $pub" >&2; exit 1; }

# Идентификатор ключа — байты 2..9 второй строки (base64), little-endian.
id=$(sed -n 2p "$pub" | base64 -d 2>/dev/null | od -An -tx1 -j2 -N8 |
    awk '{ for (i = 1; i <= NF; i++) b[n++] = $i }
         END { for (i = n - 1; i >= 0; i--) printf "%s", toupper(b[i]) }')
if [ ${#id} -ne 16 ]; then
    echo "Не удалось прочитать ключ из $pub" >&2
    exit 1
fi

for dev in $DEV_KEY_IDS; do
    if [ "$id" = "$dev" ]; then
        cat >&2 <<EOF
ОШИБКА: $pub — временный ключ разработчика ($id).
С ним выпускать нельзя. Создайте настоящий ключ:
    minisign -G -p packaging/minisign.pub -s ~/.minisign/sshdeck.key
закоммитьте packaging/minisign.pub и повторите (см. packaging/README.md).
EOF
        exit 1
    fi
done
if grep -qi "development" "$pub"; then
    echo "ОШИБКА: $pub помечен как ключ разработчика." >&2
    exit 1
fi
echo "$id"
